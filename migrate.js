export function migrateJSON(x, spec = {}) {
  const values = spec?.values || {}, dicts = spec?.dicts || {};
  const walk = (v, p) => {
    if (Array.isArray(v)) return v.map((y) => walk(y, p + '[]'));
    if (v && typeof v === 'object') {
      const o = {}, kf = own(dicts, p) ? dicts[p] : null;
      for (const [k, y] of Object.entries(v)) {
        const nk = kf ? kf(k) : tKey(k);
        if (own(o, nk)) throw new Error(`two keys become "${nk}" at ${p || '.'}`);
        o[nk] = walk(y, kf ? p + '{}' : p + '.' + k);
      }
      return o;
    }
    return typeof v === 'string' && own(values, p) ? values[p](v) : v;
  };
  return walk(x, '');
}

const isOldName = (name) => own(map().dataFiles, name) && name !== 'svet.json';
const newName = (name, dir) => (own(map().dataFiles, name + (dir ? '/' : '')) ? map().dataFiles[name + (dir ? '/' : '')].replace(/\/$/, '') : name);
const listDir = (d) => { try { return fs.readdirSync(d, { withFileTypes: true }); } catch { return []; } };
// what still has the original names in data/: [{ old, new, dir }]; conflicts = both names exist
export function dataStatus(dataDir) {
  const todo = [], conflicts = [];
  for (const e of listDir(dataDir)) {
    const key = e.isDirectory() ? e.name + '/' : e.name;
    if (!isOldName(key)) continue;
    const n = newName(e.name, e.isDirectory());
    (fs.existsSync(path.join(dataDir, n)) ? conflicts : todo).push({ old: e.name, new: n, dir: e.isDirectory() });
  }
  return { todo, conflicts };
}

// counts of what must survive the migration (the same numbers before and after)
function readJSON(f) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return null; } }
const lines = (f) => { try { return fs.readFileSync(f, 'utf8').split('\n').filter((l) => l.trim()).length; } catch { return 0; } };
const countFiles = (d) => { let n = 0; for (const e of listDir(d)) n += e.isDirectory() ? countFiles(path.join(d, e.name)) : 1; return n; };
export function counts(dataDir, names) { // names: (old name) → name in this folder
  const p = (oldName) => path.join(dataDir, names(oldName));
  const conv = readJSON(p('konverzacie.json'));
  const convList = conv ? (conv.konverzacie || conv.conversations || []) : [];
  const msgDir = p('spravy');
  let messages = 0, messageFiles = 0;
  for (const e of listDir(msgDir)) if (e.isFile() && e.name.endsWith('.json')) { messageFiles++; const a = readJSON(path.join(msgDir, e.name)); messages += Array.isArray(a) ? a.length : 0; }
  const dev = readJSON(p('zariadenia.json')) || {};
  const perm = readJSON(p('povolenia.json')) || {};
  const plans = {};
  for (const f of PLAN_FILES) {
    const j = readJSON(p(f)); if (!j) continue;
    const tasks = j.ulohy || j.tasks || {};
    plans[f] = { tasks: Object.keys(tasks).length, runs: Object.values(tasks).reduce((s, u) => s + ((u?.behy || u?.runs || []).length), 0) };
  }
  const jsonl = {};
  for (const f of ['mozog-aktivita.jsonl', 'zapisovac.jsonl']) jsonl[f] = lines(p(f));
  return {
    conversations: convList.length, messageFiles, messages,
    devices: (dev.zariadenia || dev.devices || []).length, deviceSessions: (dev.relacie || dev.sessions || []).length,
    permissionFloors: Object.keys(perm).length, permissionRules: Object.values(perm).reduce((s, a) => s + (Array.isArray(a) ? a.length : 0), 0),
    plans, jsonl, images: countFiles(p('obrazky')), attachments: countFiles(p('prilohy')), files: countFiles(dataDir),
  };
}

// one file of data/ (by original name) → new content (Buffer or string) or null = copy unchanged
function convertFile(oldRel, buf) {
  const base = path.basename(oldRel), inMessages = oldRel.startsWith('spravy/');
  const spec = inMessages ? SPEC['spravy/'] : SPEC[base] || null;
  if (base.endsWith('.jsonl')) {
    return buf.toString('utf8').split('\n').map((l) => (l.trim() ? JSON.stringify(migrateJSON(JSON.parse(l), spec)) : l)).join('\n');
  }
  if (!base.endsWith('.json') || (!inMessages && oldRel.includes('/'))) return null; // binaries, images, attachments
  const text = buf.toString('utf8');
  const indent = /^[[{]\n( +)/.exec(text.slice(0, 64))?.[1]?.length ?? 0; // keep the original formatting
  return JSON.stringify(migrateJSON(JSON.parse(text), spec), null, indent || undefined) + (text.endsWith('\n') ? '\n' : '');
}

// all files of data/ with original relative paths → { rel (new), content | src }
function plan(dataDir) {
  const out = [];
  const rename = (rel) => rel.split('/').map((seg, i, a) => { const dir = i < a.length - 1; return i === 0 ? newName(seg, dir) : seg; }).join('/');
  const walk = (rel) => {
    for (const e of listDir(path.join(dataDir, rel))) {
      const r = rel ? rel + '/' + e.name : e.name;
      if (e.isDirectory()) { walk(r); continue; }
      if (!e.isFile()) continue; // sockets, links
      out.push({ old: r, rel: rename(r) });
    }
  };
  walk('');
  return out;
}

const today = (now) => new Date(now).toLocaleDateString('sv-SE');
function backupName(root, now) {
  const base = 'data-backup-' + today(now);
  let n = base; for (let i = 2; fs.existsSync(path.join(root, n)); i++) n = `${base}-${i}`;
  return n;
}
function same(a, b) { return JSON.stringify(a) === JSON.stringify(b); }

// Migration of one instance folder. Returns a report; throws on a mismatch or conflict (nothing replaced then).
export function migrate({ root = HERE, dryRun = false, now = Date.now(), log = () => {} } = {}) {
  const report = { root, dryRun, world: null, data: null, backup: null };
  const worldFile = path.join(root, 'world.json'), svetFile = path.join(root, 'svet.json'), dataDir = path.join(root, 'data');
  // world.json
  if (!fs.existsSync(worldFile) && fs.existsSync(svetFile)) {
    const svet = JSON.parse(fs.readFileSync(svetFile, 'utf8'));
    const world = migrateWorld(svet);
    report.world = { from: 'svet.json', to: 'world.json', buildings: Object.keys(world.buildings || {}).length, floors: Object.keys(world.floors || {}).length };
    if (Object.keys(svet.budovy || {}).length !== report.world.buildings || Object.keys(svet.poschodia || {}).length !== report.world.floors) throw new Error('migrate: svet.json → world.json changed the number of buildings or floors');
    report.world.content = world;
  }
  // data/
  const st = dataStatus(dataDir);
  if (st.conflicts.length) throw new Error('migrate: data/ has both the old and the new name of ' + st.conflicts.map((c) => `${c.old} / ${c.new}`).join(', ') + ' – nothing changed, resolve it by hand');
  if (st.todo.length) {
    const before = counts(dataDir, (n) => n);
    const files = plan(dataDir);
    const staged = files.map((f) => {
      const buf = fs.readFileSync(path.join(dataDir, f.old));
      let content = null;
      try { content = convertFile(f.old, buf); } catch (e) { throw new Error(`migrate: ${f.old}: ${e.message}`); }
      return { ...f, content, buf };
    });
    // the same counts on the converted content (in memory for --dry-run, on disk after staging)
    const mem = new Map(staged.map((f) => [f.rel, f.content ?? f.buf]));
    const after = countsMem(mem, staged.length);
    report.data = { renamed: st.todo.map((t) => `${t.old}${t.dir ? '/' : ''} → ${t.new}${t.dir ? '/' : ''}`), files: staged.length, changed: staged.filter((f) => f.content !== null && f.content !== f.buf.toString('utf8')).length, before, after };
    if (!same(before, after)) throw new Error('migrate: counts differ before and after – nothing changed\nbefore ' + JSON.stringify(before) + '\nafter  ' + JSON.stringify(after));
    if (!dryRun) {
      const tmp = path.join(root, 'data.migrating');
      fs.rmSync(tmp, { recursive: true, force: true });
      for (const f of staged) {
        const dst = path.join(tmp, f.rel); fs.mkdirSync(path.dirname(dst), { recursive: true });
        if (f.content === null) { fs.copyFileSync(path.join(dataDir, f.old), dst); } else fs.writeFileSync(dst, f.content);
        try { fs.chmodSync(dst, fs.statSync(path.join(dataDir, f.old)).mode & 0o777); } catch {}
      }
      const onDisk = counts(tmp, (n) => newName(n.replace(/\/$/, ''), n.endsWith('/') || ['spravy', 'obrazky', 'prilohy'].includes(n)));
      if (!same(before, onDisk)) { fs.rmSync(tmp, { recursive: true, force: true }); throw new Error('migrate: counts differ after writing – nothing changed\nbefore ' + JSON.stringify(before) + '\nafter  ' + JSON.stringify(onDisk)); }
      report.backup = backupName(root, now);
      fs.cpSync(dataDir, path.join(root, report.backup), { recursive: true, preserveTimestamps: true }); // the original data/, untouched
      const old = path.join(root, 'data.migrating-old');
      fs.rmSync(old, { recursive: true, force: true });
      fs.renameSync(dataDir, old); fs.renameSync(tmp, dataDir); fs.rmSync(old, { recursive: true, force: true });
      log(`data/ migrated (${report.data.renamed.length} renamed, ${report.data.changed} files converted), backup ${report.backup}/`);
    }
  }
  if (report.world && !dryRun) { // last: world.json marks a finished migration
    fs.writeFileSync(worldFile, JSON.stringify(report.world.content, null, 2) + '\n');
    log('world.json created from svet.json (svet.json kept)');
  }
  if (report.world) delete report.world.content;
  report.done = !report.world && !report.data ? 'nothing to do' : dryRun ? 'dry run, nothing written' : 'migrated';
  return report;
}
// the same counts on converted content in memory (new names)
function countsMem(mem, nFiles) {
  const j = (rel) => { const b = mem.get(rel); if (b == null) return null; try { return JSON.parse(String(b)); } catch { return null; } };
  const conv = j('conversations.json');
  let messages = 0, messageFiles = 0, images = 0, attachments = 0;
  for (const [rel, b] of mem) {
    if (/^messages\/[^/]+\.json$/.test(rel)) { messageFiles++; try { const a = JSON.parse(String(b)); messages += Array.isArray(a) ? a.length : 0; } catch {} }
    if (rel.startsWith('images/')) images++;
    if (rel.startsWith('attachments/')) attachments++;
  }
  const dev = j('devices.json') || {}, perm = j('permissions.json') || {};
  const plans = {};
  for (const f of PLAN_FILES) { const x = j(newName(f)); if (!x) continue; const tasks = x.tasks || {}; plans[f] = { tasks: Object.keys(tasks).length, runs: Object.values(tasks).reduce((s, u) => s + (u?.runs || []).length, 0) }; }
  const jsonl = {};
  for (const f of ['mozog-aktivita.jsonl', 'zapisovac.jsonl']) { const b = mem.get(newName(f)); jsonl[f] = b == null ? 0 : String(b).split('\n').filter((l) => l.trim()).length; }
  return {
    conversations: (conv?.conversations || []).length, messageFiles, messages,
    devices: (dev.devices || []).length, deviceSessions: (dev.sessions || []).length,
    permissionFloors: Object.keys(perm).length, permissionRules: Object.values(perm).reduce((s, a) => s + (Array.isArray(a) ? a.length : 0), 0),
    plans, jsonl, images, attachments, files: nFiles,
  };
}
// does this folder need a migration? (cheap: no file content is read)
export function needsMigration(root = HERE) {
  const world = !fs.existsSync(path.join(root, 'world.json')) && fs.existsSync(path.join(root, 'svet.json'));
  const st = dataStatus(path.join(root, 'data'));
  return { world, data: st.todo.length > 0, conflicts: st.conflicts.map((c) => c.old) };
}

// ---------- CLI ----------
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
  const root = path.resolve(arg('--root') || HERE);
  try {
    const r = migrate({ root, dryRun: process.argv.includes('--dry-run'), log: (m) => console.log(m) });
    console.log(JSON.stringify(r, null, 1));
  } catch (e) { console.error(e.message); process.exit(1); }
}
