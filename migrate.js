// migrate.js – one-time migration of the original Slovak user data to the English names of the current code
// (step 3 of Agentic Platform, 2026-11-27).
//
// What it does:
//   svet.json → world.json   keys renamed (worldKeys), building and floor ids, paths and texts stay; svet.json stays as it is
//   data/      → data/       file names (dataFiles: konverzacie.json → conversations.json, spravy/ → messages/ …),
//                            JSON keys (keys: the same rule the code rename used, so the new code reads what the old one wrote)
//                            and the stored code values (ids of virtual floors centrala → control-center, agent veduci → lead,
//                            message types, states, task ids, MCP tool names). Texts, paths and employee names stay.
// Safety:
//   - everything is built and checked first (counts of conversations, message files and messages, devices, permissions,
//     scheduled tasks and runs, images, attachments, lines of .jsonl, all files); on any mismatch nothing is replaced
//   - before replacing, data/ is copied to data-backup-<YYYY-MM-DD>/ (an existing backup of the same day is kept, then -2, -3…)
//   - idempotent: a second run finds nothing to do; old and new names side by side = conflict, nothing is touched
//   - the server calls it at start (server.js) when world.json is missing and svet.json exists, or data/ still has old names;
//     the self-test (--selftest) only runs it dry, so a broken migration stops the restart before the old server exits
//
// CLI:  node migrate.js [--dry-run] [--root <dir>]     (default root = the folder of this file)
// The mapping is in migrate-map.json (generated by product/migrate-gen.mjs from the private rename map).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const own = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
let MAP = null;
const map = () => (MAP ||= JSON.parse(fs.readFileSync(path.join(HERE, 'migrate-map.json'), 'utf8')));

