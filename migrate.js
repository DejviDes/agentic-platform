// ---------- single values ----------
const keepCase = (r) => /^[A-Z][a-z0-9À-ɏ]*$|^[A-Z0-9]+$/.test(r);
export const tKey = (k) => (own(map().keys, k) ? map().keys[k] : k);
// a stored code value (state, type, kind…): the string rule of the code rename
export const tValue = (v) => (typeof v !== 'string' || keepCase(v) ? v : own(map().values, v) ? map().values[v] : v);
// a value made of pieces ('uloha:<hash>' → 'task:<hash>')
export const tPieces = (v) => (typeof v !== 'string' ? v : v.replace(/[A-Za-z][\w-]*/g, (c) => tValue(c)));
export function tFloor(v) {
  if (typeof v !== 'string') return v;
  const F = map().floorIds;
  if (own(F, v)) return F[v];
  for (const k of Object.keys(F)) if (k.endsWith('/') && v.startsWith(k)) return F[k] + v.slice(k.length);
  return v; // the user's own floors (<building id>/<folder name>) stay
}
// scheduled task id: renamed only where the current code uses the new id (migrate-map.json taskIds)
export const tTask = (v) => (typeof v === 'string' && own(map().taskIds || {}, v) ? map().taskIds[v] : v);
export const tAgent = (v) => (v === 'veduci' ? 'lead' : v); // employee names come from .claude/agents and stay
export function tMcp(v) {
  if (typeof v !== 'string') return v;
  const { mcpServer, mcpTools } = map();
  if (own(mcpServer, v)) return mcpServer[v];
  const m = /^mcp__mesto__(.+)$/.exec(v);
  return m ? `mcp__${mcpServer.mesto}__${own(mcpTools, m[1]) ? mcpTools[m[1]] : m[1]}` : v;
}

// ---------- svet.json → world.json ----------
const tNotes = (v) => (typeof v !== 'string' ? v : v === 'priecinok' ? 'folder' : v.replace(/\{cesta\}/g, '{path}').replace(/\{meno\}/g, '{name}'));
export function migrateWorld(svet) {
  const W = map().worldKeys;
  const wk = (k) => (own(W, k) ? W[k] : k);
  const walk = (x, p) => {
    if (Array.isArray(x)) return x.map((v) => walk(v, p + '[]'));
    if (x && typeof x === 'object') {
      const o = {};
      const dict = ['.poschodia', '.budovy', '.slovnik'].includes(p); // keys are the user's paths, building ids and words
      for (const [k, v] of Object.entries(x)) {
        const nk = dict || k.startsWith('_') ? k : wk(k);
        if (own(o, nk)) throw new Error(`svet.json: two keys become "${nk}" at ${p || '.'}`);
        o[nk] = p === '.slovnik' ? v : walk(v, dict ? p + '{}' : p + '.' + k);
      }
      return o;
    }
    if (p === '.mesto' || p === '.mozog.druh') return tValue(x); // vrstvy → layers, klasicke → classic, priecinok → folder
    if (/^\.(?:budovy|poschodia)\{\}\.poznamky(?:\.sablona)?$/.test(p)) return tNotes(x); // notes: priecinok → folder, {cesta}/{meno} → {path}/{name}
    return x;
  };
  return walk(svet, '');
}
// world.json of a folder; when it is missing and svet.json exists, the migrated content of svet.json (nothing is written)
export function legacyWorld(worldFile) {
  const svet = path.join(path.dirname(worldFile), 'svet.json');
  if (fs.existsSync(worldFile) || !fs.existsSync(svet)) return null;
  return migrateWorld(JSON.parse(fs.readFileSync(svet, 'utf8')));
}

